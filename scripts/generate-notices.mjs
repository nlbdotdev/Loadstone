import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { packageNotice } from './bundle-notices.mjs';
const root = path.resolve(import.meta.dirname, '..');
const report = JSON.parse(fs.readFileSync(0, 'utf8').replace(/^\uFEFF/, ''));
const rows = [],
  sections = [],
  missing = [];
const frontend = JSON.parse(
  fs.readFileSync(path.join(root, 'dist/frontend-notices.json'), 'utf8'),
);
if (
  frontend.schemaVersion !== 1 ||
  !Array.isArray(frontend.packages) ||
  !frontend.packages.length
)
  throw new Error('Build the renderer before generating notices.');
const records = new Map();
for (const item of Object.values(report).flat())
  for (const folder of item.paths) {
    const record = packageNotice(folder);
    records.set(`${record.name}@${record.version}`, {
      ...record,
      scopes: ['main-runtime'],
    });
  }
for (const record of frontend.packages) {
  const key = `${record.name}@${record.version}`;
  if (records.has(key)) records.get(key).scopes.push('renderer-bundle');
  else records.set(key, { ...record, scopes: ['renderer-bundle'] });
}
for (const record of [...records.values()].sort((a, b) =>
  a.name.localeCompare(b.name, 'en'),
)) {
  const { notices, renderedModules, ...metadata } = record;
  if (!notices.some((item) => /^licen[cs]e/i.test(item.name)))
    missing.push(`${record.name}@${record.version}`);
  rows.push({
    ...metadata,
    notices: notices.map(({ name, text }) => ({
      file: name,
      sha256: crypto.createHash('sha256').update(text).digest('hex'),
    })),
  });
  sections.push(
    `${record.name}@${record.version}\nDeclared license: ${record.license}\nIncluded in: ${record.scopes.join(', ')}\n\n` +
      (notices.length
        ? notices
            .map((n) => `--- ${n.name} ---\n${n.text.trimEnd()}\n`)
            .join('\n')
        : 'NOTICE GAP: No standalone license text found. Resolve before public distribution.\n'),
  );
}
const electron = JSON.parse(
  fs.readFileSync(
    path.join(root, 'node_modules/electron/package.json'),
    'utf8',
  ),
);
const electronLicense = fs
  .readFileSync(path.join(root, 'node_modules/electron/dist/LICENSE'), 'utf8')
  .replaceAll('\r\n', '\n');
sections.push(
  `Electron ${electron.version}\n\n${electronLicense.trimEnd()}\n\nThe packaged Windows runtime also carries LICENSES.chromium.html. Retain that file and LICENSE.electron.txt when distributing the application.\n`,
);
const header =
  'Loadstone third-party notices\n\nGenerated by pnpm notices from the installed main-process dependency graph, rendered frontend modules and Electron runtime. Package notices remain under their original licenses; this file does not license Loadstone itself. Build tools absent from the shipped runtime and rendered bundle are outside this inventory. Generated Vite runtime code is attributed to Vite.\n\n';
fs.mkdirSync(path.join(root, 'notices'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'notices/THIRD-PARTY.txt'),
  header + sections.join('\n' + '='.repeat(72) + '\n\n'),
);
fs.writeFileSync(
  path.join(root, 'notices/dependencies.json'),
  JSON.stringify(
    {
      packages: rows,
      electron: { version: electron.version, license: electron.license },
      missingLicenseTexts: missing,
    },
    null,
    2,
  ) + '\n',
);
console.log(
  `Recorded ${rows.length} shipped dependency packages and Electron ${electron.version}; no local paths included.`,
);
if (missing.length)
  console.warn(`Public-release notice gaps: ${missing.join(', ')}`);
