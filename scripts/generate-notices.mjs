import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root = path.resolve(import.meta.dirname, '..');
const report = JSON.parse(fs.readFileSync(0, 'utf8').replace(/^\uFEFF/, ''));
const rows = [],
  sections = [],
  missing = [];
for (const item of Object.values(report)
  .flat()
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
  for (const folder of item.paths) {
    const metadata = JSON.parse(
      fs.readFileSync(path.join(folder, 'package.json'), 'utf8'),
    );
    const files = fs
      .readdirSync(folder)
      .filter(
        (name) =>
          /^(licen[cs]e|notice)(\.|$)/i.test(name) &&
          fs.statSync(path.join(folder, name)).isFile(),
      )
      .sort();
    if (!files.some((name) => /^licen[cs]e/i.test(name)))
      missing.push(`${metadata.name}@${metadata.version}`);
    const notices = files.map((name) => ({
      name,
      text: fs
        .readFileSync(path.join(folder, name), 'utf8')
        .replaceAll('\r\n', '\n'),
    }));
    rows.push({
      name: metadata.name,
      version: metadata.version,
      license: metadata.license,
      homepage: metadata.homepage || null,
      notices: notices.map(({ name, text }) => ({
        file: name,
        sha256: crypto.createHash('sha256').update(text).digest('hex'),
      })),
    });
    sections.push(
      `${metadata.name}@${metadata.version}\nDeclared license: ${metadata.license}\n\n` +
        (notices.length
          ? notices
              .map((n) => `--- ${n.name} ---\n${n.text.trimEnd()}\n`)
              .join('\n')
          : 'NOTICE GAP: This installed package declares a license but contains no standalone license text. Resolve upstream attribution before public distribution.\n'),
    );
  }
}
const electron = JSON.parse(
  fs.readFileSync(
    path.join(root, 'node_modules/electron/package.json'),
    'utf8',
  ),
);
const electronLicense = fs
  .readFileSync(path.join(root, 'node_modules/electron/dist/LICENSE'), 'utf8')
  .replaceAll('\r\n', '\n');
sections.push(
  `Electron ${electron.version}\n\n${electronLicense.trimEnd()}\n\nThe packaged Windows runtime also carries LICENSES.chromium.html. Retain that file and LICENSE.electron.txt when distributing the application.\n`,
);
const header =
  'Loadstone third-party notices\n\nGenerated by pnpm notices from the installed production dependency graph and Electron runtime. Package notices remain under their original licenses; this file does not license Loadstone itself. Compiler-related production dependencies are included conservatively. Development-only tools are outside this inventory.\n\n';
fs.mkdirSync(path.join(root, 'notices'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'notices/THIRD-PARTY.txt'),
  header + sections.join('\n' + '='.repeat(72) + '\n\n'),
);
fs.writeFileSync(
  path.join(root, 'notices/dependencies.json'),
  JSON.stringify(
    {
      packages: rows,
      electron: { version: electron.version, license: electron.license },
      missingLicenseTexts: missing,
    },
    null,
    2,
  ) + '\n',
);
console.log(
  `Recorded ${rows.length} production packages and Electron ${electron.version}; no local paths included.`,
);
if (missing.length)
  console.warn(`Public-release notice gaps: ${missing.join(', ')}`);
